"""Blind human scoring sheet (docs/qa/r5-eval-blind.md) and its key (out/blind-key.json).

Model names are hidden behind letters, shuffled per video, so the scorer cannot tell which notes came
from which contestant. Scores use the docs/qa/r5-eval.md Part B rubric (Accuracy, Coverage, Structure,
Readability, each 1-5). After scoring:

  .venv/bin/python -m demo.notes_eval.blind --reveal          # print the letter -> contestant key
  .venv/bin/python -m demo.notes_eval.blind --reveal --out demo/notes_eval/out/dry-run
"""
from __future__ import annotations

import argparse
import random
from pathlib import Path

try:
    from . import common as C
except ImportError:  # pragma: no cover
    import common as C  # type: ignore[no-redef]

LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
RUBRIC = ("Accuracy", "Coverage", "Structure", "Readability")


def _notes_markdown(notes: dict) -> str:
    """Readable notes without anything that names the model (meta is left out on purpose)."""
    lines: list[str] = []
    cov = notes.get("cover") or {}
    if cov.get("summary"):
        lines.append(f"*Summary:* {cov['summary']}")
    for s in notes.get("sections") or []:
        lines.append(f"\n**{s.get('title', '')}**")
        body: list[str] = []
        C._strings({k: v for k, v in s.items() if k != "title"}, body)
        lines.extend(f"- {b}" for b in body)
    if notes.get("glossary"):
        lines.append("\n**Glossary**")
        lines.extend(f"- {g.get('term')}: {g.get('definition')}" for g in notes["glossary"])
    return "\n".join(lines)


def _scrub_names(text: str, contestants: list[str]) -> str:
    """Belt and braces: drop provider/model names that a model may have written into its own notes."""
    for cid in contestants:
        c = C.CONTESTANTS[cid]
        for name in {cid, c["provider"], C.model_of(cid)}:
            if name and len(name) >= 4:
                text = text.replace(name, "[model]")
    return text


def build(videos: list[str], contestants: list[str], seed: int | None = None) -> tuple[str, dict]:
    rng = random.Random(seed) if seed is not None else random.SystemRandom()
    key: dict = {"note": "Key to unblind docs/qa/r5-eval-blind.md. Do not open before scoring.", "videos": {}}
    parts = ["# R5 evaluation: blind scoring sheet",
             "",
             "Generated by `python -m demo.notes_eval.run_eval`. The notes below come from different models; "
             "the letters are shuffled per video and the key is in `lecture-notes-ai/demo/notes_eval/out/blind-key.json` "
             "(not in git). **Do not open the key until every table is filled.**",
             "",
             "How to score (same rubric as `docs/qa/r5-eval.md` Part B): watch or skim the video, read each set "
             "of notes, and give 1-5 for **Accuracy** (no wrong facts), **Coverage** (all main points), "
             "**Structure** (clear headings, lecture order) and **Readability** (easy to study from). "
             "Then run `python -m demo.notes_eval.blind --reveal` and copy the averages into r5-eval.md.",
             ""]
    for vid in videos:
        runs = {}
        for cid in contestants:
            r = C.read_json(C.run_path(cid, vid, 1))
            if isinstance(r, dict) and r.get("status") == "success":
                runs[cid] = r
        if not runs:
            continue
        order = list(runs)
        rng.shuffle(order)
        letters = {LETTERS[i]: cid for i, cid in enumerate(order)}
        key["videos"][vid] = {L: {"contestant": cid, "provider": C.CONTESTANTS[cid]["provider"],
                                  "model": C.model_of(cid)} for L, cid in letters.items()}
        parts += [f"## {C.VIDEOS.get(vid, vid)}", "", f"Video: https://www.youtube.com/watch?v={vid}", "",
                  "| Notes | " + " | ".join(RUBRIC) + " | Average |",
                  "|---|" + "---|" * (len(RUBRIC) + 1)]
        parts += [f"| {L} |" + " |" * (len(RUBRIC) + 1) for L in letters]
        parts.append("")
        for L, cid in letters.items():
            parts += [f"<details><summary>Notes {L}</summary>", "",
                      _scrub_names(_notes_markdown(runs[cid]["notes"]), contestants), "", "</details>", ""]
    if not key["videos"]:
        parts.append("_No successful runs yet: run the evaluation first._")
    return "\n".join(parts) + "\n", key


def write_sheet(videos: list[str], contestants: list[str], sheet: Path, key_path: Path,
                seed: int | None = None) -> dict:
    text, key = build(videos, contestants, seed)
    sheet = Path(sheet)
    sheet.parent.mkdir(parents=True, exist_ok=True)
    sheet.write_text(text, encoding="utf-8")
    C.write_json(Path(key_path), key)
    return key


def reveal(key_path: Path) -> str:
    key = C.read_json(Path(key_path)) or {}
    rows = ["| Video | Letter | Contestant | Model |", "|---|---|---|---|"]
    for vid, letters in (key.get("videos") or {}).items():
        for L, v in letters.items():
            rows.append(f"| {vid} | {L} | {v['contestant']} | {v['provider']}/{v['model']} |")
    return "\n".join(rows)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(prog="python -m demo.notes_eval.blind")
    ap.add_argument("--reveal", action="store_true")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    if a.out:
        C.set_out(a.out)
    if a.reveal:
        print(reveal(C.OUT / "blind-key.json"))
