"""Judging (Gemini as LLM-as-a-judge), code checks and aggregation -> out/evaluation.json.

Judge calls (all cached to out/, so reruns only do missing work):
  gold      once per video : 12-15 key facts from the transcript       -> out/gold/<video>.json (auto-generated, editable)
  per-run   once per run   : coverage of each gold fact + atomic-claim faithfulness + rubric 1-10
                                                                        -> out/judgements/<contestant>/<video>/<n>.json
  pairwise  per video pair : anonymised A/B comparison (run 1 notes, randomised order)
                                                                        -> out/judgements/pairwise/<video>/<a>__<b>.json
Code checks (no LLM): grounding check (numbers + quoted terms appear in transcript), noise leakage.
"""
from __future__ import annotations

import hashlib
import itertools
import json
import random
import re
import statistics as st
import time
from typing import Any, Callable

import common as C

JUDGE_PACE_SEC = 6.0           # min gap between judge calls (free-tier RPM)
HALLUCINATION_GATE = 0.10      # max hallucination rate to pass the gate
SUCCESS_GATE = 0.90
W_QUALITY, W_SPEED, W_HEADROOM = 0.60, 0.25, 0.15

_last_call = [0.0]


class JudgeQuota(Exception):
    pass


def _judge(system: str, user: str, max_tokens: int = 8192) -> Any:
    from notes_engine import llm
    k = C.key("GEMINI_API_KEY")
    gap = time.time() - _last_call[0]
    if gap < JUDGE_PACE_SEC:
        time.sleep(JUDGE_PACE_SEC - gap)
    client = llm._Client(C.JUDGE_PROVIDER, k, C.judge_model())
    try:
        return client.ask_json((system, user), max_tokens, 0.0)
    except llm.LLMError as e:
        msg = C.scrub(str(e))
        if C.classify_error(msg).startswith("quota"):
            raise JudgeQuota(msg) from None
        raise
    finally:
        _last_call[0] = time.time()


# ------------------------------------------------------------------------- prompts ----
GOLD_SYS = """You extract the key facts a student must learn from a lecture transcript. Use ONLY the transcript.
Return JSON: {"facts": [{"id": "f1", "fact": "<one self-contained sentence>"}, ...]} with 12 to 15 facts.
Prefer central concepts, definitions, numbers and conclusions over anecdotes. No sponsor/promo content."""

RUN_SYS = """You are a strict evaluator of AI-generated study notes. You get the lecture TRANSCRIPT (ground truth),
a list of KEY FACTS, and the NOTES. Judge only against the transcript; do not use outside knowledge to excuse claims.

Return JSON exactly:
{
 "coverage": [{"id": "f1", "covered": true|false}],            // one entry per key fact: do the notes state it (paraphrase ok)?
 "claims": [{"claim": "<atomic factual claim from the notes>", "supported": true|false, "why": "<short>"}],
 "rubric": {"accuracy": 1-10, "coverage": 1-10, "clarity": 1-10, "structure": 1-10, "overall": 1-10,
            "rationale": "<2-3 sentences>"}
}
For "claims": pick 20 atomic factual claims spread across the whole notes (or all, if fewer). "supported" = the
transcript states or directly implies it. Generic textbook statements that the transcript does not make count as
NOT supported."""

PAIR_SYS = """You compare two sets of AI-generated study notes (A and B) for the same lecture transcript.
Decide which would better help a student learn THIS lecture: accuracy to the transcript first, then coverage,
then clarity and structure. Ignore length unless it hurts usefulness.
Return JSON: {"winner": "A"|"B"|"tie", "reason": "<1-2 sentences>"}"""


def _tx_block(t: dict) -> str:
    return f"TITLE: {t.get('title')}\nTRANSCRIPT:\n{C.transcript_text(t)}"


# --------------------------------------------------------------------- judge stages ----
def ensure_gold(vid: str, t: dict, dry: bool, log: Callable) -> dict | None:
    p = C.GOLD / f"{vid}.json"
    g = C.read_json(p)
    if isinstance(g, dict) and g.get("facts"):
        return g
    if dry:
        log(f"would extract gold facts {vid}")
        return None
    log(f"gold facts {vid}")
    obj = _judge(GOLD_SYS, _tx_block(t))
    facts = [f for f in (obj.get("facts") if isinstance(obj, dict) else []) or [] if isinstance(f, dict) and f.get("fact")]
    for i, f in enumerate(facts):
        f["id"] = f"f{i + 1}"
    g = {"video": vid, "auto_generated": True, "editable": True,
         "note": "Auto-generated by the judge model from the transcript. Edit freely; delete out/judgements to re-judge.",
         "generator": f"{C.JUDGE_PROVIDER}/{C.judge_model()}", "facts": facts[:15]}
    C.write_json(p, g)
    return g


def gold_hash(g: dict) -> str:
    return hashlib.sha1(json.dumps(g.get("facts"), sort_keys=True).encode()).hexdigest()[:10]


def judge_run(cid: str, vid: str, n: int, t: dict, gold: dict, dry: bool, log: Callable) -> None:
    rp = C.run_path(cid, vid, n)
    run = C.read_json(rp)
    if not isinstance(run, dict) or run.get("status") != "success":
        return
    jp = C.JUDGE / cid / vid / f"{n}.json"
    old = C.read_json(jp)
    if isinstance(old, dict) and old.get("gold_hash") == gold_hash(gold):
        return
    if dry:
        log(f"would judge {cid} {vid} #{n}")
        return
    log(f"judge {cid} {vid} #{n}")
    facts = "\n".join(f"{f['id']}: {f['fact']}" for f in gold["facts"])
    user = f"{_tx_block(t)}\n\nKEY FACTS:\n{facts}\n\nNOTES:\n{C.notes_text(run['notes'])}"
    obj = _judge(RUN_SYS, user)
    if not isinstance(obj, dict):
        raise ValueError("judge returned non-object")
    C.write_json(jp, {"contestant": cid, "video": vid, "run": n, "gold_hash": gold_hash(gold),
                      "judge": f"{C.JUDGE_PROVIDER}/{C.judge_model()}", "result": obj})


def judge_pair(vid: str, a: str, b: str, t: dict, dry: bool, log: Callable) -> None:
    ra, rb = C.read_json(C.run_path(a, vid, 1)), C.read_json(C.run_path(b, vid, 1))
    if not (isinstance(ra, dict) and isinstance(rb, dict) and ra.get("status") == rb.get("status") == "success"):
        return
    jp = C.JUDGE / "pairwise" / vid / f"{a}__{b}.json"
    if C.read_json(jp):
        return
    if dry:
        log(f"would compare {vid} {a} vs {b}")
        return
    rng = random.Random(f"{vid}:{a}:{b}")
    swap = rng.random() < 0.5
    first, second = (rb, ra) if swap else (ra, rb)
    log(f"pairwise {vid} {a} vs {b} (swap={swap})")
    user = (f"{_tx_block(t)}\n\nNOTES A:\n{C.notes_text(first['notes'])}\n\nNOTES B:\n{C.notes_text(second['notes'])}")
    obj = _judge(PAIR_SYS, user, 2048)
    w = str((obj or {}).get("winner", "")).strip().upper() if isinstance(obj, dict) else ""
    label = {"A": (b if swap else a), "B": (a if swap else b)}.get(w, "tie")
    C.write_json(jp, {"video": vid, "a": a, "b": b, "shown_first": first["contestant"], "raw_winner": w,
                      "winner": label, "reason": (obj or {}).get("reason", "") if isinstance(obj, dict) else ""})


def judge_all(ts: dict, videos: list[str], contestants: list[str], runs: int, dry: bool, log: Callable) -> None:
    try:
        for vid in videos:
            if vid not in ts:
                continue
            gold = ensure_gold(vid, ts[vid], dry, log)
            if not gold:
                continue
            for n in range(1, runs + 1):
                for cid in contestants:
                    try:
                        judge_run(cid, vid, n, ts[vid], gold, dry, log)
                    except JudgeQuota:
                        raise
                    except Exception as e:  # noqa: BLE001
                        log(f"  judge failed {cid} {vid} #{n}: {C.scrub(str(e))[:160]}")
            for a, b in itertools.combinations(contestants, 2):
                try:
                    judge_pair(vid, a, b, ts[vid], dry, log)
                except JudgeQuota:
                    raise
                except Exception as e:  # noqa: BLE001
                    log(f"  pairwise failed {vid} {a}/{b}: {C.scrub(str(e))[:160]}")
    except JudgeQuota as e:
        log(f"JUDGE QUOTA HIT, stopping judging (rerun later to resume): {e}")
        C.write_json(C.OUT / "judge_quota.json", {"when": time.strftime("%Y-%m-%d %H:%M:%S"), "error": str(e)})


# ---------------------------------------------------------------------- code checks ----
_NUMWORDS = {"zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8,
             "nine": 9, "ten": 10, "eleven": 11, "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15,
             "sixteen": 16, "seventeen": 17, "eighteen": 18, "nineteen": 19, "twenty": 20, "thirty": 30,
             "forty": 40, "fifty": 50, "hundred": 100, "thousand": 1000, "million": 10 ** 6, "billion": 10 ** 9}
NOISE = [r"\bsubscrib\w*", r"\bsponsor\w*", r"\blike (the|this) video\b", r"\bsmash (that|the) like\b",
         r"\bhit the bell\b", r"\bnotification bell\b", r"\bpatreon\b", r"\blink in the description\b",
         r"\bdescription below\b", r"\bpromo code\b", r"\bdiscount code\b", r"\bcomment below\b",
         r"\bthanks for watching\b", r"\bmy channel\b", r"\bbrilliant\.org\b"]


def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", re.sub(r"[^\w.%$ ]+", " ", s.lower())).strip()


def grounding(notes: dict, t: dict) -> dict:
    txt = C.notes_text(notes)
    tr = C.transcript_text(t).lower()
    trn = _norm(tr)
    tr_nums = set(re.findall(r"\d+(?:\.\d+)?", tr.replace(",", "")))
    for w, v in _NUMWORDS.items():
        if re.search(rf"\b{w}\b", tr):
            tr_nums.add(str(v))
    nums = set(re.findall(r"(?<![\w.])\d+(?:\.\d+)?", txt.replace(",", "")))
    nums = {x for x in nums if x not in {"0", "1", "2"}}   # trivially common, skip
    num_ok = sorted(x for x in nums if x in tr_nums or x.rstrip("0").rstrip(".") in tr_nums)
    num_bad = sorted(nums - set(num_ok))
    quoted = set()
    for m in re.finditer(r"[\"\u201c\u2018`']([^\"\u201d\u2019`'\n]{3,60})[\"\u201d\u2019`']", txt):
        q = m.group(1).strip()
        if len(q.split()) <= 8 and re.search(r"[A-Za-z]", q):
            quoted.add(q)
    q_ok = sorted(q for q in quoted if _norm(q) and _norm(q) in trn)
    q_bad = sorted(quoted - set(q_ok))
    total = len(nums) + len(quoted)
    return {"numbers_checked": len(nums), "numbers_grounded": len(num_ok), "numbers_ungrounded": num_bad[:20],
            "quotes_checked": len(quoted), "quotes_grounded": len(q_ok), "quotes_ungrounded": q_bad[:20],
            "grounding_rate": round((len(num_ok) + len(q_ok)) / total, 3) if total else None}


def noise(notes: dict, t: dict) -> dict:
    txt = C.notes_text(notes).lower()
    tr = C.transcript_text(t).lower()
    hits = {}
    for pat in NOISE:
        k = len(re.findall(pat, txt))
        if k:
            hits[pat.strip("\\b")] = k
    words = max(1, len(txt.split()))
    src = sum(len(re.findall(p, tr)) for p in NOISE)
    return {"hits": hits, "count": sum(hits.values()), "per_1k_words": round(1000 * sum(hits.values()) / words, 2),
            "transcript_noise_hits": src}


# ---------------------------------------------------------------------- aggregation ----
def _pct(xs: list[float], q: float) -> float | None:
    if not xs:
        return None
    xs = sorted(xs)
    k = (len(xs) - 1) * q
    lo, hi = int(k), min(len(xs) - 1, int(k) + 1)
    return round(xs[lo] + (xs[hi] - xs[lo]) * (k - lo), 2)


def _mean(xs: list) -> float | None:
    xs = [x for x in xs if x is not None]
    return round(sum(xs) / len(xs), 4) if xs else None


def _bool(v: Any) -> bool:
    return v is True or str(v).lower() == "true"


def aggregate() -> dict:
    from notes_engine.llm import PROVIDERS
    runs_out, per = [], {}
    for cid in C.CONTESTANTS:
        for vid in C.VIDEOS:
            t = C.read_json(C.TRANSCRIPTS / f"{vid}.json")
            for p in sorted((C.RUNS / cid / vid).glob("*.json")) if (C.RUNS / cid / vid).exists() else []:
                r = C.read_json(p)
                if not isinstance(r, dict) or p.suffix != ".json":
                    continue
                n = r.get("run")
                tm = r.get("timing") or {}
                if r.get("status") == "error":
                    r["error_type"] = C.classify_error(r.get("error") or "")
                row = {"contestant": cid, "model": r.get("model"), "video": vid, "run": n, "status": r.get("status"),
                       "latency_sec": r.get("latency_sec"), "error_type": r.get("error_type"),
                       "error": r.get("error"), "schema_valid": r.get("schema_valid"),
                       "http_requests": tm.get("http_requests"), "http_statuses": tm.get("http_statuses"),
                       "sleep_sec": tm.get("sleep_sec"), "http_sec": tm.get("http_sec"),
                       "output_tokens": tm.get("output_tokens"), "prompt_tokens": tm.get("prompt_tokens"),
                       "started": r.get("started")}
                if r.get("status") == "success" and t:
                    notes = r["notes"]
                    row["sections"] = len(notes.get("sections") or [])
                    row["output_chars"] = len(json.dumps(notes, ensure_ascii=False))
                    row["output_words"] = len(C.notes_text(notes).split())
                    row["grounding"] = grounding(notes, t)
                    row["noise"] = noise(notes, t)
                    if r.get("latency_sec") and tm.get("sleep_sec") is not None:
                        row["wait_share"] = round(tm["sleep_sec"] / r["latency_sec"], 3)
                    if tm.get("output_tokens") and tm.get("http_sec"):
                        row["tokens_per_sec"] = round(tm["output_tokens"] / tm["http_sec"], 1)
                    j = C.read_json(C.JUDGE / cid / vid / f"{n}.json")
                    if isinstance(j, dict):
                        res = j.get("result") or {}
                        cov = [c for c in res.get("coverage") or [] if isinstance(c, dict)]
                        claims = [c for c in res.get("claims") or [] if isinstance(c, dict)]
                        rub = res.get("rubric") or {}
                        if cov:
                            row["recall"] = round(sum(_bool(c.get("covered")) for c in cov) / len(cov), 3)
                            row["facts_judged"] = len(cov)
                        if claims:
                            bad = [c for c in claims if not _bool(c.get("supported"))]
                            row["hallucination_rate"] = round(len(bad) / len(claims), 3)
                            row["claims_judged"] = len(claims)
                            row["unsupported_claims"] = [{"claim": str(c.get("claim"))[:240], "why": str(c.get("why"))[:200]}
                                                         for c in bad][:8]
                        if isinstance(rub, dict):
                            def num(k):
                                try:
                                    return float(rub.get(k))
                                except (TypeError, ValueError):
                                    return None
                            row["rubric"] = {k: num(k) for k in ("accuracy", "coverage", "clarity", "structure", "overall")}
                            row["rubric_rationale"] = str(rub.get("rationale", ""))[:600]
                runs_out.append(row)
    # pairwise
    pairs = []
    pdir = C.JUDGE / "pairwise"
    for p in sorted(pdir.glob("*/*.json")) if pdir.exists() else []:
        j = C.read_json(p)
        if isinstance(j, dict):
            pairs.append(j)

    contestants = []
    for cid, c in C.CONTESTANTS.items():
        rs = [r for r in runs_out if r["contestant"] == cid]
        att = [r for r in rs if r["status"] in ("success", "error")]
        ok = [r for r in rs if r["status"] == "success"]
        lat = [r["latency_sec"] for r in ok if r.get("latency_sec") is not None]
        errs: dict[str, int] = {}
        for r in rs:
            if r["status"] != "success":
                errs[r.get("error_type") or "other"] = errs.get(r.get("error_type") or "other", 0) + 1
        overall = [r["rubric"]["overall"] for r in ok if r.get("rubric") and r["rubric"].get("overall") is not None]
        # consistency: per video, |overall run1 - run2|, averaged
        diffs = []
        for vid in C.VIDEOS:
            sc = [r["rubric"]["overall"] for r in ok if r["video"] == vid and r.get("rubric") and r["rubric"].get("overall") is not None]
            if len(sc) >= 2:
                diffs.append(st.pstdev(sc))
        wins = games = 0.0
        for pj in pairs:
            if cid in (pj["a"], pj["b"]):
                games += 1
                wins += 1.0 if pj["winner"] == cid else (0.5 if pj["winner"] == "tie" else 0.0)
        tps = [r["tokens_per_sec"] for r in ok if r.get("tokens_per_sec") is not None]
        ws = [r["wait_share"] for r in ok if r.get("wait_share") is not None]
        gr = [r["grounding"]["grounding_rate"] for r in ok if r.get("grounding") and r["grounding"]["grounding_rate"] is not None]
        statuses: dict[str, int] = {}
        for r in rs:
            for k, v in (r.get("http_statuses") or {}).items():
                statuses[k] = statuses.get(k, 0) + v
        reqs = sum(statuses.values())
        contestants.append({
            "id": cid, "provider": c["provider"], "label": PROVIDERS[c["provider"]]["label"], "model": C.model_of(cid),
            "available": True, "runs_planned": len(C.VIDEOS) * 2, "runs_recorded": len(rs), "attempted": len(att),
            "succeeded": len(ok), "success_rate": round(len(ok) / len(att), 3) if att else None,
            "errors": errs, "quota_daily_hit": errs.get("quota_daily", 0) > 0,
            "schema_valid_rate": round(sum(1 for r in ok if r.get("schema_valid")) / len(ok), 3) if ok else None,
            "latency_p50": _pct(lat, 0.5), "latency_p95": _pct(lat, 0.95),
            "latency_n": len(lat),
            "output_words_mean": _mean([r.get("output_words") for r in ok]),
            "sections_mean": _mean([r.get("sections") for r in ok]),
            "tokens_per_sec_mean": _mean(tps),
            "wait_share_mean": _mean(ws),
            "http_requests": reqs, "http_429": statuses.get("429", 0),
            "recall_mean": _mean([r.get("recall") for r in ok]),
            "hallucination_rate_mean": _mean([r.get("hallucination_rate") for r in ok]),
            "grounding_rate_mean": _mean(gr),
            "noise_per_1k_mean": _mean([r["noise"]["per_1k_words"] for r in ok if r.get("noise")]),
            "noise_hits_total": sum(r["noise"]["count"] for r in ok if r.get("noise")),
            "rubric_mean": {k: _mean([r["rubric"].get(k) for r in ok if r.get("rubric")])
                            for k in ("accuracy", "coverage", "clarity", "structure", "overall")},
            "rubric_judged": len(overall),
            "consistency_sd": round(sum(diffs) / len(diffs), 3) if diffs else None,
            "consistency_pairs": len(diffs),
            "pairwise_games": int(games), "pairwise_win_rate": round(wins / games, 3) if games else None,
        })

    # decision
    p50s = [c["latency_p50"] for c in contestants if c["latency_p50"]]
    fastest = min(p50s) if p50s else None
    for c in contestants:
        gates = []
        if c["success_rate"] is None or c["success_rate"] < SUCCESS_GATE:
            gates.append(f"success rate < {int(SUCCESS_GATE * 100)}%")
        if c["hallucination_rate_mean"] is None:
            gates.append("hallucination rate not measured")
        elif c["hallucination_rate_mean"] > HALLUCINATION_GATE:
            gates.append(f"hallucination rate > {int(HALLUCINATION_GATE * 100)}%")
        ov = c["rubric_mean"]["overall"]
        parts = [(0.4, ov / 10 if ov is not None else None), (0.3, c["recall_mean"]),
                 (0.2, 1 - c["hallucination_rate_mean"] if c["hallucination_rate_mean"] is not None else None),
                 (0.1, c["pairwise_win_rate"])]
        have = [(w, v) for w, v in parts if v is not None]
        quality = sum(w * v for w, v in have) / sum(w for w, _ in have) if have else None
        speed = (fastest / c["latency_p50"]) if (fastest and c["latency_p50"]) else None
        headroom = None
        if c["wait_share_mean"] is not None:
            headroom = (1 - c["wait_share_mean"]) * (0.0 if c["quota_daily_hit"] else 1.0)
        comp = None
        if None not in (quality, speed, headroom):
            comp = W_QUALITY * quality + W_SPEED * speed + W_HEADROOM * headroom
        c["decision"] = {"gates_failed": gates, "passes_gates": not gates,
                         "quality": round(quality, 4) if quality is not None else None,
                         "speed": round(speed, 4) if speed is not None else None,
                         "headroom": round(headroom, 4) if headroom is not None else None,
                         "composite": round(comp, 4) if comp is not None else None}
    ranked = sorted(contestants, key=lambda c: (not c["decision"]["passes_gates"],
                                                -(c["decision"]["composite"] if c["decision"]["composite"] is not None else -1)))
    for i, c in enumerate(ranked):
        c["rank"] = i + 1
    ev = {"generated": time.strftime("%Y-%m-%d %H:%M:%S"),
          "judge": f"{C.JUDGE_PROVIDER}/{C.judge_model()}",
          "judge_quota": C.read_json(C.OUT / "judge_quota.json"),
          "constants": {"success_gate": SUCCESS_GATE, "hallucination_gate": HALLUCINATION_GATE,
                        "w_quality": W_QUALITY, "w_speed": W_SPEED, "w_headroom": W_HEADROOM,
                        "judge_pace_sec": JUDGE_PACE_SEC},
          "videos": [{"id": v, "label": lbl,
                      "duration_sec": (C.read_json(C.TRANSCRIPTS / f"{v}.json") or {}).get("duration_sec"),
                      "transcript_chars": len(C.transcript_text(C.read_json(C.TRANSCRIPTS / f"{v}.json") or {})),
                      "gold_facts": len((C.read_json(C.GOLD / f"{v}.json") or {}).get("facts") or []),
                      "gold": (C.read_json(C.GOLD / f"{v}.json") or {}).get("facts") or []}
                     for v, lbl in C.VIDEOS.items()],
          "contestants": ranked,
          "unavailable": [{"id": k, "reason": v} for k, v in C.UNAVAILABLE.items()],
          "runs": runs_out, "pairwise": pairs}
    C.write_json(C.OUT / "evaluation.json", ev)
    return ev


if __name__ == "__main__":
    aggregate()
    print("wrote", C.OUT / "evaluation.json")
